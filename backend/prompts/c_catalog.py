def normalize_c_topic(project: str) -> str:
    p = (project or "").lower().strip()
    if "stack" in p: return "stack"
    if "queue" in p: return "queue"
    if "linked" in p and "list" in p: return "linked_list"
    if any(term in p for term in ["pointer", "ptr", "address", "dereferenc"]): return "pointers"
    if any(term in p for term in ["struct", "structure", "record", "typedef"]): return "structures"
    if any(term in p for term in ["file", "fopen", "fread", "fwrite", "fprintf", "fscanf"]): return "file_handling"
    if "recursi" in p: return "recursion"
    if any(term in p for term in ["loop", "for loop", "while", "do-while", "iterat"]): return "loop"
    if any(term in p for term in ["function", "method", "param", "call by"]): return "functions"
    if any(term in p for term in ["array", "matrix", "grid", "vector"]) or bool(re.search(r"\blists?\b", p)): return "array"
    if "search" in p and "tree" not in p: return "searching"
    if "sort" in p: return "sorting"
    if any(term in p for term in ["string", "strtok", "char*", "strlen", "strcpy"]): return "strings"
    if (bool(re.search(r"\b(bits?|bitwise|bitmask|mask|xor|shift)\b", p)) or ("binary" in p and "tree" not in p and "search" not in p)): return "bitwise"
    if any(term in p for term in ["dma", "malloc", "calloc", "realloc", "dynamic memory"]): return "dma"
    return "dynamic_topic"

