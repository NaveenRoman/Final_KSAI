def normalize_cpp_topic(project: str) -> str:
    p = (project or "").lower().strip()
    if "stack" in p: return "stack"
    if "queue" in p: return "queue"
    if "linked" in p and "list" in p: return "linked_list"
    if any(term in p for term in ["tree", "bst", "binary search tree"]): return "trees"
    if any(term in p for term in ["exception", "throw", "try", "catch"]): return "exception_handling"
    if any(term in p for term in ["file", "fstream", "ifstream", "ofstream"]) or bool(re.search(r"\b(io|file handling)\b", p)): return "file_handling"
    if any(term in p for term in ["inherit"]): return "inheritance"
    if any(term in p for term in ["polymorph", "virtual", "abstract", "interface", "override"]): return "polymorphism"
    if any(term in p for term in ["loop", "while", "iteration"]) or bool(re.search(r"\b(for loop|do-while)\b", p)): return "loops"
    if any(term in p for term in ["function", "method", "lambda", "callback"]) or bool(re.search(r"\bparam\b", p)): return "functions"
    if any(term in p for term in ["pointer", "smart pointer", "unique_ptr", "shared_ptr"]) or bool(re.search(r"\bptr\b", p)): return "pointers"
    if any(term in p for term in ["struct", "structure"]): return "structures"
    if any(term in p for term in ["class", "object", "encapsul", "constructor"]) or bool(re.search(r"\boop\b", p)): return "oop"
    if any(term in p for term in ["thread", "multithread", "mutex", "concurrency", "async"]): return "multithreading"
    if any(term in p for term in ["stl", "vector", "unordered_map", "iterator"]) or bool(re.search(r"\b(map|set)\b", p)): return "stl"
    if any(term in p for term in ["array", "matrix", "grid"]) or bool(re.search(r"\blists?\b", p)): return "arrays"
    if "search" in p: return "searching"
    if "sort" in p: return "sorting"
    if any(term in p for term in ["string", "substring", "text"]) or bool(re.search(r"\bstr\b", p)): return "strings"
    return "dynamic_topic"

